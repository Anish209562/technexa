const executable=resolve('node_modules/agent-browser/bin/agent-browser-win32-x64.exe')
const origin=process.env.PREVIEW_URL || 'http://localhost:5174'
mkdirSync('artifacts',{recursive:true})
const report=[]
const limitations=[]
function browser(...args) {
  const data=JSON.parse(execFileSync(executable,['--session','tnx-interactions','--download-path',resolve('artifacts'),'--json',...args],{encoding:'utf8',timeout:60000,windowsHide:true,maxBuffer:5*1024*1024}).trim())
  if(!data.success) throw Error(JSON.stringify(data))
  return data.data
}
