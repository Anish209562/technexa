check('Portfolio keyboard navigation moves selection and focus',evaluate('document.querySelector(".gallery-index button:nth-child(3)").getAttribute("aria-selected")==="true" && document.activeElement===document.querySelector(".gallery-index button:nth-child(3)")'))
